        write_cmd = f"cat > {temp_file} << 'EOF'\n{hosts_content}\nEOF"
        
        result = ssh_client.execute_command(write_cmd, print_output=False)
        if result['rc'] != 0:
            logger.error(f"Failed to write temporary hosts file: {result['stderr']}")
