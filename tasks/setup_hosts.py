def configure_firewall_local(logger) -> bool:
    try:
        logger.info("Configuring firewall to open database ports")
        
        # Check if firewalld is installed and running
        check_result = subprocess.run(
            ["systemctl", "is-active", "firewalld"],
            capture_output=True,
            text=True
        )
        
        if check_result.returncode != 0:
            logger.info("firewalld is not active, skipping firewall configuration")
            return True
        
        ports = [5432, 25010, 27017, 3306, 33060, 9042, 9142]
        
        for port in ports:
            logger.info(f"Opening port {port}")
            result = subprocess.run(
                ["firewall-cmd", "--permanent", "--add-port", f"{port}/tcp"],
                capture_output=True,
                text=True
            )
            if result.returncode != 0:
                logger.warning(f"Failed to add port {port}: {result.stderr}")
        
        logger.info("Reloading firewall configuration")
        result = subprocess.run(
            ["firewall-cmd", "--reload"],
            capture_output=True,
            text=True
        )
        if result.returncode != 0:
            logger.error(f"Failed to reload firewall: {result.stderr}")
            return False
        
        logger.info("Successfully configured firewall")
        return True
        
    except FileNotFoundError:
        logger.info("firewall-cmd not found, skipping firewall configuration")
        return True
    except Exception as e:
        logger.error(f"Error configuring firewall: {str(e)}")
        return False


def configure_sshd_remote(ssh_client: SSHClient, logger) -> bool:
    try:
        sshd_config = "/etc/ssh/sshd_config"
        
        logger.info("Backing up existing sshd_config")
        backup_result = ssh_client.execute_command(f"sudo cp {sshd_config} {sshd_config}.backup", print_output=False)
        if backup_result['rc'] != 0:
            logger.warning(f"Could not backup sshd_config: {backup_result['stderr']}")
        
        logger.info("Modifying SSHD configuration")
        
        # Use sed to modify the configuration in place
        commands = [
            # Change or add PasswordAuthentication
            f"sudo sed -i 's/^#*PasswordAuthentication.*/PasswordAuthentication yes/' {sshd_config}",
            # Change or add PermitRootLogin
            f"sudo sed -i 's/^#*PermitRootLogin.*/PermitRootLogin yes/' {sshd_config}",
            # Change or add LoginGraceTime
            f"sudo sed -i 's/^#*LoginGraceTime.*/LoginGraceTime 0/' {sshd_config}",
        ]
        
        for cmd in commands:
            result = ssh_client.execute_command(cmd, print_output=False)
            if result['rc'] != 0:
                logger.warning(f"Command failed: {cmd}\nError: {result['stderr']}")
        
        # Verify settings exist, if not append them
        verify_and_add = """
if ! grep -q '^PasswordAuthentication' /etc/ssh/sshd_config; then
    echo 'PasswordAuthentication yes' | sudo tee -a /etc/ssh/sshd_config
fi
if ! grep -q '^PermitRootLogin' /etc/ssh/sshd_config; then
    echo 'PermitRootLogin yes' | sudo tee -a /etc/ssh/sshd_config
fi
if ! grep -q '^LoginGraceTime' /etc/ssh/sshd_config; then
    echo 'LoginGraceTime 0' | sudo tee -a /etc/ssh/sshd_config
fi
"""
        result = ssh_client.execute_command(verify_and_add, print_output=False)
        if result['rc'] != 0:
            logger.warning(f"Could not verify/add settings: {result['stderr']}")
        
        # Set proper permissions
        result = ssh_client.execute_command(f"sudo chmod 600 {sshd_config}", print_output=False)
        if result['rc'] != 0:
            logger.warning(f"Could not set permissions on sshd_config: {result['stderr']}")
        
        # Remove cloud-init override config if exists
        cloud_init_config = "/etc/ssh/sshd_config.d/50-cloud-init.conf"
        logger.info(f"Removing {cloud_init_config} if exists")
        result = ssh_client.execute_command(f"sudo rm -f {cloud_init_config}", print_output=False)
        if result['rc'] != 0:
            logger.warning(f"Could not remove {cloud_init_config}: {result['stderr']}")
        
        # Restart SSHD
        logger.info("Restarting SSHD service")
        result = ssh_client.execute_command("sudo systemctl restart sshd", print_output=False)
        if result['rc'] != 0:
            logger.error(f"Failed to restart SSHD: {result['stderr']}")
            return False
        
        logger.info("Successfully configured SSHD")
        return True
        
    except Exception as e:
        logger.error(f"Error configuring SSHD: {str(e)}")
        return False


def setup_hosts_locally(config, logger, verbose: bool = True,
                        machine_name: str = "raptor",
                        configure_sshd: bool = True,
                        **kwargs) -> bool:
    all_machines = config.get_machines()
    root_password = config.get_custom_variable('pwd')
    timezone = config.get_custom_variable('timezone')

    hostname = f"{machine_name}.demo.guardium"
    logger.info(f"Setting hostname to {hostname}")
    if not set_hostname_local(hostname, logger):
        logger.error("✗ Failed to set hostname")
        return False

    if timezone:
        logger.info(f"Setting timezone to {timezone}")
        if not set_timezone_local(timezone, logger):
            logger.error("✗ Failed to set timezone")
            return False

    logger.info("Configuring /etc/hosts")
    hosts_content = generate_hosts_content(all_machines)
    if not update_hosts_file_local(hosts_content, logger):
        logger.error("✗ Failed to update /etc/hosts")
        return False

    if configure_sshd:
        logger.info("Configuring SSHD")
        if not configure_sshd_local(logger):
            logger.error("✗ Failed to configure SSHD")
            return False

    if root_password:
        logger.info("Setting root password")
        if not set_root_password_local(root_password, logger):
            logger.error("✗ Failed to set root password")
            return False

    logger.info("Configuring firewall for database ports")
    if not configure_firewall_local(logger):
        logger.warning("Failed to configure firewall (non-critical)")

    logger.info(f"✓ {machine_name} local setup completed")
    return True


def setup_hosts_on_remote_machine(config, logger, verbose: bool = True,
                                  use_private_ip: bool = True,
                                  ssh_port: int = 2223,
                                  configure_sshd: bool = True,
                                  **kwargs) -> bool:
    all_machines = config.get_machines()
    credentials = {
        'username': config.get_custom_variable('username', 'root'),
        'password': config.get_custom_variable('password'),
        'ssh_key': config.get_custom_variable('ssh_private_key')
    }
    root_password = config.get_custom_variable('pwd')
    timezone = config.get_custom_variable('timezone')
    remote_machines = config.get('tasks', {}).get('remote_machines', [])
    windows_machines = config.get('tasks', {}).get('windows_machines', [])

    hosts_content = generate_hosts_content(all_machines)

    for machine_name in remote_machines:
        if config.is_appliance(machine_name):
            logger.info(f"  Skipping appliance: {machine_name}")
            continue
        if machine_name in windows_machines:
            logger.info(f"  Skipping Windows machine: {machine_name}")
            continue

        machine_info = config.get_machine(machine_name)
        if not machine_info:
            logger.warning(f"  {machine_name} not found in configuration — skipping")
            continue

        username = credentials.get('username', 'root')
        host = machine_info.get('private_ip') if use_private_ip else machine_info.get('host')
        if not host and use_private_ip:
            host = machine_info.get('host')
        if not host:
            logger.error(f"✗ No IP address for {machine_name}")
            return False

        logger.info(f"  Setting up {machine_name} ({host})")
        try:
            with SSHClient(host=host, username=username, port=ssh_port) as ssh:
                hostname = f"{machine_name}.demo.guardium"
                if not set_hostname_remote(ssh, hostname, logger):
                    logger.error(f"✗ Failed to set hostname on {machine_name}")
                    return False

                if timezone and not set_timezone_remote(ssh, timezone, logger):
                    logger.error(f"✗ Failed to set timezone on {machine_name}")
                    return False

                if not update_hosts_file_remote(ssh, hosts_content, logger):
                    logger.error(f"✗ Failed to update /etc/hosts on {machine_name}")
                    return False

                if configure_sshd and not configure_sshd_remote(ssh, logger):
                    logger.error(f"✗ Failed to configure SSHD on {machine_name}")
                    return False

                if root_password and not set_root_password_remote(ssh, root_password, logger):
                    logger.error(f"✗ Failed to set root password on {machine_name}")
                    return False

                logger.info(f"  ✓ {machine_name} setup completed")

        except Exception as e:
            logger.error(f"✗ Failed to setup {machine_name}: {str(e)}")
            return False

    return True


def create_demo_user_on_ceratops(config, logger, verbose=True,
                                  ceratops_machine: str = "ceratops",
                                  ssh_username: str = "itzuser",
                                  demo_username: str = "demo",
                                  debug: bool = False, **kwargs) -> bool:
    _header(logger, "CREATE DEMO USER ON CERATOPS (WINDOWS)")

    try:
        with _ceratops_ssh(config, logger, ceratops_machine, ssh_username) as ssh:
            if ssh is None:
                return False
            pwd = config.get_custom_variable('pwd')
            if not pwd:
                logger.error("✗ pwd not found in custom_variables")
                return False
            commands = [
                f'net user {demo_username} "{pwd}" /add',
                f'net localgroup Administrators {demo_username} /add',
            ]
            for cmd in commands:
                logger.info(f"  ➜ {cmd}")
                result = ssh.execute_command(cmd, print_output=verbose)
                if result['rc'] != 0:
                    combined = (result['stdout'] + result['stderr']).lower()
                    if "already" in combined or "member" in combined or result['rc'] == 128:
                        logger.info(f"  ℹ Already exists, skipping")
                    else:
                        logger.error(f"✗ Command failed (rc={result['rc']}): {result['stderr'].strip() or result['stdout'].strip()}")
                        return False
                else:
                    logger.info("  ✓ OK")
            logger.info(f"✓ User '{demo_username}' created and added to Administrators on {ceratops_machine}")
            return True
    except Exception as e:
        logger.error(f"✗ Unexpected error: {e}")
        if debug:
            import traceback
            logger.error(traceback.format_exc())
        return False


def copy_files_to_ceratops(config, logger, verbose=True,
                           ceratops_machine: str = "ceratops",
                           ssh_username: str = "itzuser",
                           dest_dir: str = r'C:\bootcamp',
                           source_dirs: list = None,
                           debug: bool = False, **kwargs) -> bool:
    _header(logger, "COPY AGENT FILES TO CERATOPS")

    ceratops_ip = config.get_machine_ip(ceratops_machine, use_private=True)
    ssh_private_key = config.get_custom_variable('ssh_private_key')

    try:
        with _ceratops_ssh(config, logger, ceratops_machine, ssh_username) as ssh:
            if ssh is None:
                return False
            mkdir_cmd = f'mkdir "{dest_dir}"'
            logger.info(f"  ➜ {mkdir_cmd}")
            result = ssh.execute_command(mkdir_cmd, print_output=verbose)
            if result['rc'] != 0:
                combined = (result['stdout'] + result['stderr']).lower()
                if "already exists" in combined or "file exists" in combined:
                    logger.info("  ℹ Directory already exists, skipping")
                else:
                    logger.error(f"✗ mkdir failed (rc={result['rc']}): {result['stderr'].strip()}")
                    return False
            else:
                logger.info(f"  ✓ Created {dest_dir}")

        # ── SCP each source_dir to ceratops (outside SSH session) ────────────────
        scp_base = ["scp", "-r", "-P", "2223", "-o", "StrictHostKeyChecking=no", "-o", "BatchMode=yes"]
        with _tmp_ssh_key(ssh_private_key, logger) as key_file:
            if key_file:
                scp_base += ["-i", key_file]
            for src in source_dirs:
                dir_name = os.path.basename(src.rstrip("/"))
                remote_dest = f"{ssh_username}@{ceratops_ip}:{dest_dir}\\{dir_name}"
                cmd = scp_base + [src, remote_dest]
                logger.info(f"  ➜ scp {src} → {remote_dest}")
                proc = subprocess.run(cmd, capture_output=True, text=True)
                if proc.returncode != 0:
                    logger.error(f"✗ scp failed (rc={proc.returncode}): {proc.stderr.strip()}")
                    return False
                logger.info(f"  ✓ Copied {dir_name}")

        logger.info(f"✓ Agent files copied to {ceratops_machine}:{dest_dir}")
        return True
    except Exception as e:
        logger.error(f"✗ Unexpected error: {e}")
